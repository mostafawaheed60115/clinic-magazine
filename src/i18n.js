export const messages = { ar, en };
export function t(key) {
  return (
    messages[locale][key] ??
    messages.en[key] ??
    ({
      discover: locale === "ar" ? "اكتشف المجموعة" : "Discover the collection",
      unavailableImage:
        locale === "ar" ? "الصورة غير متاحة" : "Image unavailable",
    }[key] ||
      key)
  );
}
export function setLocale(value) {
  locale = value === "en" ? "en" : "ar";
  document.documentElement.lang = locale;
  document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
  try {
    localStorage.setItem("clinic-locale", locale);
  } catch {
    /* session-only locale */
  }
}
export function initLocale() {
  setLocale(locale);
}
export const nameOf = (item) => item?.[`name_${locale}`] || item?.name_en || "";
export const number = (value) =>
  new Intl.NumberFormat(locale === "ar" ? "ar-EG" : "en-EG").format(value ?? 0);
export const money = (value) =>
  new Intl.NumberFormat(locale === "ar" ? "ar-EG" : "en-EG", {
    style: "currency",
    currency: "EGP",
    maximumFractionDigits: 2,
  }).format(Number(value) || 0);
